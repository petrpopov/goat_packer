//! A lattice of integer translations in Hermite normal form (design 2026-11-02, §9.2).
//!
//! The basis is `(s, 0)` and `(t, h)` with `s, h > 0` and `0 <= t < s`, so two bases of the
//! same lattice have the same form: it is the dedup key of the enumeration and the coset
//! index of the phase histogram. A coset of the lattice (a "phase": every lattice shifted by
//! one translation) is numbered `r * s + x_mod`, where `r = y mod h` and `x_mod` is the
//! x position after the rows below it are sheared back by `t` per `h` rows.

/// A 2D lattice `{ i * (s, 0) + j * (t, h) }`.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct Hnf {
    pub s: i32,
    pub t: i32,
    pub h: i32,
}

/// Inclusive pixel box `(min_x, min_y, max_x, max_y)`.
pub type PixelBox = (i32, i32, i32, i32);

impl Hnf {
    /// The lattice generated by `u` and `w`; `None` when they are parallel (or zero).
    pub fn from_basis(u: (i64, i64), w: (i64, i64)) -> Option<Hnf> {
        let det = (u.0 * w.1 - u.1 * w.0).abs();
        if det == 0 {
            return None;
        }
        // A lattice point on the lowest row above the x axis fixes the shear.
        let (h, i, j) = extended_gcd(u.1, w.1);
        let s = det / h;
        let t = (i * u.0 + j * w.0).rem_euclid(s);
        Some(Hnf {
            s: i32::try_from(s).ok()?,
            t: i32::try_from(t).ok()?,
            h: i32::try_from(h).ok()?,
        })
    }

    /// Area of one cell in pixels, and the number of cosets.
    pub fn det(&self) -> i64 {
        i64::from(self.s) * i64::from(self.h)
    }

    pub fn cosets(&self) -> usize {
        self.det() as usize
    }

    /// The coset of the translation `(x, y)`.
    pub fn coset_of(&self, x: i32, y: i32) -> usize {
        let (row, r) = (y.div_euclid(self.h), y.rem_euclid(self.h));
        let x_mod =
            (i64::from(x) - i64::from(row) * i64::from(self.t)).rem_euclid(i64::from(self.s));
        r as usize * self.s as usize + x_mod as usize
    }

    /// The translations of `coset` inside `bounds`, rows from the bottom, left to right.
    pub fn points_in(&self, coset: usize, bounds: PixelBox) -> Vec<(i32, i32)> {
        let mut points: Vec<(i32, i32)> = self.walker().points(coset, bounds).collect();
        points.sort_unstable_by_key(|&(x, y)| (y, x));
        points
    }

    /// The lattice with its short basis ready for walking points (build once, ask often).
    pub fn walker(&self) -> Walker {
        let [u, w] = self.reduced();
        let (u, w) = (
            (i64::from(u.0), i64::from(u.1)),
            (i64::from(w.0), i64::from(w.1)),
        );
        Walker {
            hnf: *self,
            u,
            w,
            cross: u.0 * w.1 - u.1 * w.0,
        }
    }

    /// The lattice vectors (a Lagrange-reduced basis: the shortest vector first, the angle
    /// between them within 60 to 120 degrees), oriented so the first points up.
    pub fn reduced(&self) -> [(i32, i32); 2] {
        let norm2 = |v: (i64, i64)| v.0 * v.0 + v.1 * v.1;
        let mut u = (i64::from(self.s), 0);
        let mut w = (i64::from(self.t), i64::from(self.h));
        if norm2(u) > norm2(w) {
            std::mem::swap(&mut u, &mut w);
        }
        loop {
            let dot = u.0 * w.0 + u.1 * w.1;
            let m = (2 * dot + norm2(u)).div_euclid(2 * norm2(u));
            w = (w.0 - m * u.0, w.1 - m * u.1);
            if norm2(w) >= norm2(u) {
                break;
            }
            std::mem::swap(&mut u, &mut w);
        }
        let up = |v: (i64, i64)| {
            if v.1 < 0 || (v.1 == 0 && v.0 < 0) {
                (-v.0, -v.1)
            } else {
                v
            }
        };
        let (u, w) = (up(u), up(w));
        [(u.0 as i32, u.1 as i32), (w.0 as i32, w.1 as i32)]
    }
}

/// Points of the cosets of one lattice inside a box, walked along the short basis: the HNF
/// rows can be one pixel apart with one point in thousands (`h = 1`, `s` huge), the short
/// basis visits about as many cells as the box holds points.
#[derive(Clone, Copy, Debug)]
pub struct Walker {
    hnf: Hnf,
    u: (i64, i64),
    w: (i64, i64),
    /// `u x w`, never zero.
    cross: i64,
}

impl Walker {
    /// The translations of `coset` inside `bounds` (inclusive), in no particular order.
    pub fn points(&self, coset: usize, bounds: PixelBox) -> impl Iterator<Item = (i32, i32)> {
        let (min_x, min_y, max_x, max_y) = bounds;
        let s = self.hnf.s as usize;
        let origin = ((coset % s) as i64, (coset / s) as i64);
        let (u, w, cross) = (self.u, self.w, self.cross as f64);
        // Coordinates of the box corners in the basis, relative to the coset's own point.
        let coords = [
            (min_x, min_y),
            (max_x, min_y),
            (min_x, max_y),
            (max_x, max_y),
        ]
        .map(|(x, y)| {
            let (dx, dy) = (
                (i64::from(x) - origin.0) as f64,
                (i64::from(y) - origin.1) as f64,
            );
            (
                (dx * w.1 as f64 - dy * w.0 as f64) / cross,
                (u.0 as f64 * dy - u.1 as f64 * dx) / cross,
            )
        });
        let range = |pick: fn(&(f64, f64)) -> f64| {
            let low = coords.iter().map(pick).fold(f64::INFINITY, f64::min);
            let high = coords.iter().map(pick).fold(f64::NEG_INFINITY, f64::max);
            (low.floor() as i64)..=(high.ceil() as i64)
        };
        let js = range(|c| c.1);
        range(|c| c.0).flat_map(move |i| {
            js.clone().filter_map(move |j| {
                let (x, y) = (origin.0 + i * u.0 + j * w.0, origin.1 + i * u.1 + j * w.1);
                let inside = x >= i64::from(min_x)
                    && x <= i64::from(max_x)
                    && y >= i64::from(min_y)
                    && y <= i64::from(max_y);
                inside.then_some((x as i32, y as i32))
            })
        })
    }
}

/// `(g, i, j)` with `g = gcd(a, b) > 0` and `i * a + j * b = g`.
fn extended_gcd(a: i64, b: i64) -> (i64, i64, i64) {
    let (mut old, mut rest) = (a, b);
    let (mut old_i, mut i) = (1, 0);
    let (mut old_j, mut j) = (0, 1);
    while rest != 0 {
        let q = old / rest;
        (old, rest) = (rest, old - q * rest);
        (old_i, i) = (i, old_i - q * i);
        (old_j, j) = (j, old_j - q * j);
    }
    if old < 0 {
        (-old, -old_i, -old_j)
    } else {
        (old, old_i, old_j)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn two_bases_of_one_lattice_give_one_form() {
        let a = Hnf::from_basis((6, 1), (2, 5)).unwrap();
        // Add a multiple of one vector to the other, flip a sign, swap.
        let b = Hnf::from_basis((-(2 + 3 * 6), -(5 + 3)), (6, 1)).unwrap();
        assert_eq!(a, b);
        assert_eq!(a.det(), 28);
        assert!(Hnf::from_basis((2, 4), (-1, -2)).is_none());
    }

    #[test]
    fn cosets_partition_the_plane_and_points_in_agree_with_coset_of() {
        let lattice = Hnf::from_basis((7, 2), (-3, 6)).unwrap();
        let bounds = (-20, -15, 25, 18);
        let mut seen = vec![0usize; lattice.cosets()];
        for y in bounds.1..=bounds.3 {
            for x in bounds.0..=bounds.2 {
                seen[lattice.coset_of(x, y)] += 1;
            }
        }
        for (coset, &expected) in seen.iter().enumerate() {
            let points = lattice.points_in(coset, bounds);
            assert_eq!(points.len(), expected, "coset {coset}");
            assert!(points.iter().all(|&(x, y)| lattice.coset_of(x, y) == coset));
        }
    }

    #[test]
    fn lattice_vectors_stay_in_the_zero_coset() {
        let lattice = Hnf::from_basis((7, 2), (-3, 6)).unwrap();
        for (x, y) in [(7, 2), (-3, 6), (4, 8), (10, -4)] {
            assert_eq!(lattice.coset_of(x, y), 0);
        }
        assert_ne!(lattice.coset_of(1, 0), 0);
    }

    #[test]
    fn reduction_finds_short_vectors_of_a_skewed_basis() {
        let lattice = Hnf::from_basis((1000, 1), (999, 1)).unwrap();
        let [u, w] = lattice.reduced();
        assert_eq!(u.0 * w.1 - u.1 * w.0, 1);
        assert!(
            u.0.abs() + u.1.abs() <= 2 && w.0.abs() + w.1.abs() <= 2,
            "{u:?} {w:?}"
        );
        let wide = Hnf::from_basis((10, 0), (3, 10)).unwrap();
        let [u, w] = wide.reduced();
        let dot = i64::from(u.0 * w.0 + u.1 * w.1);
        let norm2 = i64::from(u.0 * u.0 + u.1 * u.1);
        assert!(2 * dot.abs() <= norm2);
        assert!(w.0 * w.0 + w.1 * w.1 >= u.0 * u.0 + u.1 * u.1);
    }
}
